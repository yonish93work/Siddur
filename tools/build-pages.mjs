// Builds data/pages.json (PDF page -> printed page label) from the page headers of source/siddur.pdf.
// Run again whenever the PDF changes:  npm run pages
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { getDocument } from 'pdfjs-dist/legacy/build/pdf.mjs';

const PDF = new URL('../source/siddur.pdf', import.meta.url);
const OUT = new URL('../data/pages.json', import.meta.url);

// The PDF's old Hebrew font stores each letter as an ASCII character (see the appendix in CLAUDE.md).
const ASCII = '`abcdefghijklmnopqrstuvwxyz', HEB = 'אבגדהוזחטיךכלםמןנסעףפץצקרשת';
const toHeb = s => [...s].map(c => (ASCII.includes(c) ? HEB[ASCII.indexOf(c)] : c === 'W' ? 'ש' : c)).join('');
const VALUE = { א: 1, ב: 2, ג: 3, ד: 4, ה: 5, ו: 6, ז: 7, ח: 8, ט: 9, י: 10, כ: 20, ל: 30, מ: 40, נ: 50, ס: 60, ע: 70, פ: 80, צ: 90, ק: 100, ר: 200, ש: 300, ת: 400 };
const gematria = s => [...s].reduce((a, c) => a + (VALUE[c] ?? NaN), 0);

const bytes = readFileSync(PDF);
const sha256 = createHash('sha256').update(bytes).digest('hex');
const doc = await getDocument({ data: new Uint8Array(bytes), verbosity: 0 }).promise;
const pages = [];

for (let n = 1; n <= doc.numPages; n++) {
  const items = (await (await doc.getPage(n)).getTextContent()).items.filter(i => i.str.trim())
    .map(i => ({ s: i.str, x: i.transform[4], y: i.transform[5] }));
  const high = items.filter(i => i.y > 770);
  const top = Math.max(...high.map(i => i.y));
  const line = high.filter(i => Math.abs(i.y - top) < 6).sort((a, b) => b.x - a.x);
  let raw = '', prev = null;
  for (const i of line) {
    if (prev !== null && prev - i.x > 22) raw += ' ';
    raw += toHeb(i.s); prev = i.x;
  }
  raw = raw.replace(/\s+/g, ' ').trim();
  // Digits come out right-to-left like everything else on the line; read them left-to-right instead.
  const digits = line.filter(i => /\d/.test(i.s)).sort((a, b) => a.x - b.x).map(i => i.s.trim()).join('');
  const notes = [];
  let printed = null, label = null, header = raw;
  const token = raw.match(/(?:^|\s)\d+([א-ת]?)(?=\s|$)/);
  const isHeader = raw.length < 60 && !/[¦¨§¤¥]/.test(raw);
  if (isHeader && /^\d{1,3}$/.test(digits) && token) {
    printed = Number(digits); label = digits + token[1];
    const words = raw.replace(token[0], ' ').trim().split(/\s+/);
    // The Hebrew-letter number is the first or last word of the header.
    const ends = [words[0], words.at(-1)].filter(w => w && /^[א-ת]{1,4}$/.test(w));
    const letters = ends.find(w => gematria(w) === printed || (token[1] && gematria(w) === printed + 1));
    if (letters) words.splice(words.lastIndexOf(letters), 1);
    header = words.join(' ');
  } else if (!isHeader) header = '';
  pages.push({ pdf: n, printed, label, header, check: false, notes });
}

// Headers that cannot be read automatically, checked by eye (2026-11-25).
const OVERRIDES = {
  400: ['387', 'מגילת אסתר'],       // no number printed; the table of contents says 387
  565: ['526', 'מנחה לתשעה באב'],  // no number printed; the table of contents says 526
  619: ['575', 'זבד הבת'],         // no number printed; the table of contents says 575
  692: ['660', 'פרקי אבות ו'],     // decorated header, prints 660
  704: [null, 'משלי'], 728: [null, 'קריאות התורה'], 770: [null, 'שער התוספות'],  // divider pages without a number
};
for (const [n, [label, header]] of Object.entries(OVERRIDES)) {
  Object.assign(pages[n - 1], { label, printed: label ? Number(label) : null, header, check: false, notes: ['checked by eye'] });
}
const skip = new Set(Object.keys(OVERRIDES).map(Number));

// Opening pages of chapters show a title and no number: fill the number in when the neighbours leave exactly that room.
for (let i = 5; i < pages.length; i++) {
  if (pages[i].printed !== null || skip.has(i + 1)) continue;
  let j = i; while (j < pages.length && pages[j].printed === null && !skip.has(j + 1)) j++;
  const before = pages[i - 1]?.printed ?? 0, after = pages[j]?.printed;
  if (after == null) { i = j - 1; continue; }
  for (let k = i; k < j; k++) {
    const guess = after - (j - k);
    if (guess > before) {
      pages[k].printed = guess; pages[k].label = String(guess); pages[k].check = true;
      pages[k].notes.push('no number in header; inferred from neighbours');
    } else { pages[k].check = true; pages[k].notes.push('no number in header, and no free number between its neighbours'); }
  }
  i = j;
}

const seen = new Map();
for (const p of pages) if (p.label) seen.set(p.label, [...(seen.get(p.label) ?? []), p]);
for (const [label, twins] of seen) if (twins.length > 1) for (const p of twins) {
  p.check = true; p.notes.push(`same printed number ${label} on PDF pages ${twins.map(t => t.pdf).join(', ')}`);
}

writeFileSync(OUT, JSON.stringify({
  description: 'PDF page -> printed page number for source/siddur.pdf. Generated by tools/build-pages.mjs from the page headers. Entries with check=true need a visual check.',
  sha256, pdfPages: doc.numPages, pages,
}, null, 1) + '\n');
console.log(`${doc.numPages} pages, ${pages.filter(p => p.label).length} numbered, ${pages.filter(p => p.check).length} to check, ${[...seen.values()].filter(t => t.length > 1).length} duplicated numbers`);
