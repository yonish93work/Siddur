// Turns the list into groups of { title, from, to } with PDF pages. A section ends right before the next one;
// if the next one opens in the middle of a page (no title banner), that page belongs to both.
export function buildMenu(idx) {
  const bounds = [...new Set(TOC.filter(e => !e[3]).map(e => idx.first(e[0])))].sort((a, b) => a - b);
  const opensPage = n => {
    const p = idx.pages[n - 1];
    return p.label === null || p.notes.some(x => x.includes('inferred') || x.includes('checked by eye'));
  };
  const groups = new Map();
  for (const [from, title, group, to] of TOC) {
    if (!group) continue;
    const a = idx.first(from);
    let b;
    if (to) b = idx.last(to);
    else {
      const nextStart = bounds.find(x => x > a);
      b = nextStart === undefined ? idx.pages.length : opensPage(nextStart) ? nextStart - 1 : nextStart;
    }
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push({ title, from: a, to: b });
  }
  return groups;
}
